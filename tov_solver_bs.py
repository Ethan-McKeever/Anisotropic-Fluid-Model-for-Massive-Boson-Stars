@jit(nopython=True)
def eos(rho,vec_rho,vec_p):
    for i in range(0,len(vec_rho)-1):
        if(rho<=vec_rho[0]):
            print('ERROR_1')
            break
        elif((rho>vec_rho[i])and(rho<=vec_rho[i+1])):
            gg=np.log(vec_p[i+1]/vec_p[i])/np.log(vec_rho[i+1]/vec_rho[i])
            p=vec_p[i]*((rho/vec_rho[i])**gg)
            Gamma=((rho+p)/rho)*gg
        elif(rho>vec_rho[-1]):
            print('ERROR_2')
            break
    return(p,Gamma)

@jit(nopython=True)
def eos_inv(p,vec_p,vec_rho):
    for i in range(0,len(vec_p)-1):
        if(p<=vec_p[0]):
            print('ERROR_3')
            break
        elif((p>vec_p[i])and(p<=vec_p[i+1])):
            gg=np.log(vec_p[i+1]/vec_p[i])/np.log(vec_rho[i+1]/vec_rho[i])
            rho=vec_rho[i]*((p/vec_p[i])**(1.0/gg))
            Gamma=((rho+p)/rho)*gg
        elif(p>vec_p[-1]):
            print('ERROR_4')
            break
    return(rho,Gamma)

@jit(nopython=True)
def dmdr(r,rho):
    mp=4.0*np.pi*(r**2.0)*rho
    return(mp)

@jit(nopython=True)
def dnudr(r,m,p):
    nup=(2.0*(m+(4.0*np.pi*(r**3.0)*p)))/(r*(r-(2.0*m)))
    return(nup)

@jit(nopython=True)
def dpdr(r,p,m,rho,lmb0,lmb1,lmb2,n,c1,c2,c3,c4,set_of_bs):
    if(set_of_bs=='1'):
        f=((lmb0+(lmb1*(r**n))+(lmb2*(r**(c1*n))))*r)/(2.0*(lmb0+1.0))
    elif(set_of_bs=='2'):
        f=((lmb0+(lmb1*(r**n)))*r)/(2.0*(lmb0+1.0))
    elif(set_of_bs=='3'):
        f=((lmb0*(r**c2))+(lmb1*(r**n))+((lmb2+c3)*((np.log(r+1.0))**c4)))/(2.0*(lmb0+1.0))
    pp=-(1.0/(1.0+((2.0*f)/r)))*(((rho+p)*(m+(4.0*np.pi*(r**3.0)*p)))/(r*(r-(2.0*m))))
    return(pp)

@jit(nopython=True)
def mr(rho_0, vec_rho, vec_p, lmb0, lmb1, lmb2, n, c1, c2, c3, c4, radius):

    eos_vars = eos(rho_0, vec_rho, vec_p)
    p_0 = eos_vars[0]
    Gamma_0 = eos_vars[1]
    nu_0 = 0.0
    m_3 = 4.0*np.pi*rho_0

    sgm02 = -((2.0*np.pi)/3.0)*(lmb0/((2.0*lmb0)+1.0))*(rho_0+p_0)*(rho_0+(3.0*p_0))
    p_2 = -(((4.0*np.pi)/3.0)*(rho_0+p_0)*(rho_0+(3.0*p_0)))-(2.0*sgm02)
    rho_2 = (p_2*(rho_0+p_0))/(Gamma_0*p_0)
    nu_2 = ((8.0*np.pi)/3.0)*(rho_0+(3.0*p_0))
    m_5 = 2.0*np.pi*rho_2

    dr = 1.0e-03
    r_min = 5.0e-03

    r = r_min
    m = ((1.0/3.0)*m_3*(r**3.0))+((1.0/5.0)*m_5*(r**5.0))
    nu = nu_0+((1.0/2.0)*nu_2*(r**2.0))
    p = p_0+((1.0/2.0)*p_2*(r**2.0))
    rho = rho_0+((1.0/2.0)*rho_2*(r**2.0))

    while (p >= vec_p[0] and r < radius):

        h = min(dr, radius-r) # make the final step land exactly at radius

        s1 = dmdr(r, rho)
        s2 = dmdr(r+(h/2.0), rho)
        s3 = dmdr(r+(h/2.0), rho)
        s4 = dmdr(r+h, rho)

        t1 = dpdr(r, p, m, rho, lmb0, lmb1, lmb2, n, c1, c2, c3, c4, set_of_bs)
        t2 = dpdr(r+(h/2.0), p+(t1*(h/2.0)), m, rho, lmb0, lmb1, lmb2, n, c1, c2, c3, c4, set_of_bs)
        t3 = dpdr(r+(h/2.0), p+(t2*(h/2.0)), m, rho, lmb0, lmb1, lmb2, n, c1, c2, c3, c4, set_of_bs)
        t4 = dpdr(r+h, p+(t3*h), m, rho, lmb0, lmb1, lmb2, n, c1, c2, c3, c4, set_of_bs)

        u1 = dnudr(r, m, p)
        u2 = dnudr(r+(h/2.0), m, p)
        u3 = dnudr(r+(h/2.0), m, p)
        u4 = dnudr(r+h, m, p)

        dp = (t1+(2.0*t2)+(2.0*t3)+t4)*(h/6.0)
        p = p + dp

        # EOS pressure boundary is reached first
        if p < vec_p[0]:
            p = p - dp
            break

        m = m+((s1+(2.0*s2)+(2.0*s3)+s4)*(h/6.0))
        nu = nu+((u1+(2.0*u2)+(2.0*u3)+u4)*(h/6.0))
        rho = eos_inv(p, vec_p, vec_rho)[0]
        r = r+h

    r_s = r
    m_s = m
    p_s = p
    rho_s = rho

    return (r_s, m_s, p_0, rho_0, p_s, rho_s)

